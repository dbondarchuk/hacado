export const ORGANIZATION_SLUG_BLOCKLIST: ReadonlySet<string> = new Set(
  BLOCKLIST_ENTRIES,
);

export function isOrganizationSlugBlocked(slug: string): boolean {
  return ORGANIZATION_SLUG_BLOCKLIST.has(slug.toLowerCase());
}

export function isOrganizationSlugFormatValid(slug: string): boolean {
  return (
    slug.length >= ORGANIZATION_SLUG_MIN_LENGTH &&
    ORGANIZATION_SLUG_REGEX.test(slug)
  );
}

export function getOrganizationSlugIssue(slug: string): OrganizationSlugIssue {
  if (!slug || slug.length < ORGANIZATION_SLUG_MIN_LENGTH) {
    return "too_short";
  }
  if (!ORGANIZATION_SLUG_REGEX.test(slug)) {
    return "invalid";
  }
  if (isOrganizationSlugBlocked(slug)) {
    return "reserved";
  }
  return null;
}
